// Denormalize to full shape matching APPOINTMENT_FIELDS GraphQL fragment
export const APPOINTMENTS = raw.map((a) => ({
  id: a.id,
  start_datetime: a.start,
  end_datetime: a.end,
  duration_minutes: byId(SERVICES, a.serviceId)?.duration_minutes ?? 15,
  status: a.status,
  notes: a.notes,
  cancellation_reason: a.cancellation_reason,
  reminder_sent_at: null,
  created_at: a.start,
  updated_at: a.start,
  patient: byId(PATIENTS, a.patientId),
  clinician: byId(CLINICIANS, a.clinicianId),
  clinic: byId(CLINICS, a.clinicId),
  room: byId(ROOMS, a.roomId),
  service: byId(SERVICES, a.serviceId),
  booked_by_user: null,
  // Video fields — online services get a room id
  video_room_id: byId(SERVICES, a.serviceId)?.is_online ? `room_${a.id}_${Math.random().toString(36).slice(2, 8)}` : null,
}))

// Status-based helpers used by multiple pages
export const getAppointmentsByStatus = (status) => APPOINTMENTS.filter((a) => a.status === status)
export const getAppointmentsByPatient = (patientId) => APPOINTMENTS.filter((a) => a.patient?.id === patientId)
export const getAppointmentsByClinician = (clinicianId) => APPOINTMENTS.filter((a) => a.clinician?.id === clinicianId)
export const getAppointmentsByClinic = (clinicId) => APPOINTMENTS.filter((a) => a.clinic?.id === clinicId)
export const getAppointmentsByDate = (dateStr) => APPOINTMENTS.filter((a) => a.start_datetime.startsWith(dateStr))
